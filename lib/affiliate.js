// 共有URL用の短いslugを作る(紛らわしい文字 0/o/1/l は使わない)
export function makeSlug() {
  const chars = "abcdefghijkmnpqrstuvwxyz23456789";
  let s = "";
  for (let i = 0; i < 8; i++) s += chars[Math.floor(Math.random() * chars.length)];
  return s;
}
